// The token radar's model, radar-2: one sealed snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) and every other protocol that passes the watchlist's own rule below
// the floor: pre-token, not a versioned pool, not a wrapped, staked or bridged
// product of a token that already trades. A wrapped or staked product is not a
// launch waiting to happen, so the board holds no Bridge, Canonical Bridge,
// Liquid Staking, Liquid Restaking, Restaked BTC or CEX row at all.
//
// Implied value follows only from the snapshot's own figures, priced off the
// market the snapshot itself records:
//
//   multiple   = median(mcap_usd / tvl_usd) over live-token protocols in the
//                same category (at least 3 of them, else the global median),
//                clamped to [0.05, 1.50]
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4  (age unknown: 365)
//   breadth    = 1 + 0.02 x min(max(chains - 1, 0), 5)
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity x breadth))
//
// The multiple is what the market already pays per dollar of TVL for this kind
// of protocol: a Dex earns its multiple from Dexs that trade, a lender from
// lenders that trade. No protocol name is ever special-cased: the same
// function scores every row, and the multiples are recomputed from the
// snapshot on every run.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

